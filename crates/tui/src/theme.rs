pub fn get(name: &str) -> Palette {
    THEMES
        .iter()
        .find(|t| t.name == name)
        .copied()
        .unwrap_or(THEMES[0])
}

pub fn next(name: &str) -> Palette {
    let idx = THEMES.iter().position(|t| t.name == name).unwrap_or(0);
    THEMES[(idx + 1) % THEMES.len()]
}

pub fn names() -> Vec<&'static str> {
    THEMES.iter().map(|t| t.name).collect()
}
